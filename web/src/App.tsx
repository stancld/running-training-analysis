import { useState } from 'react';
import { DATA } from './data';
import { Diary } from './Diary';
import { day, hm, phaseShort, raceOf, useWide } from './format';
import { Heatmap, Ledger } from './History';
import { PlanChart } from './Plan';
import { Fitness, Guardrails, RailChips, ThisWeek } from './Week';

const P = DATA.plan;
const curIdx = P.findIndex(p => p.start === DATA.weeks.find(w => w.current)?.start);

function Track() {
  const phases: { code: string; name: string; a: number; b: number }[] = [];
  P.forEach((p, i) => {
    const last = phases[phases.length - 1];
    if (last?.code === p.phase) last.b = i;
    else phases.push({ code: p.phase, name: p.phase_name, a: i, b: i });
  });
  return (
    <div className="track" aria-label={curIdx >= 0 ? `Week ${curIdx + 1} of ${P.length}` : `${P.length}-week plan`}>
      <p className="eyebrow">{curIdx >= 0 ? `Week ${curIdx + 1} of ${P.length}` : `${P.length}-week plan`}</p>
      <div className="track-row" style={{ gridTemplateColumns: `repeat(${P.length}, 1fr)` }}>
        {P.map((p, i) => (
          <i key={p.start} className={i < curIdx ? 'done' : i === curIdx ? 'cur' : p.race ? 'race' : ''}
            title={`Week ${p.index} · ${day(p.start)}${p.race ? ` · ${p.race}` : ''}`} />
        ))}
        {phases.map(ph => (
          <span key={ph.code} className={curIdx >= ph.a && curIdx <= ph.b ? 'on' : ''}
            style={{ gridColumn: `${ph.a + 1} / ${ph.b + 2}` }} title={ph.name}>
            <b>{ph.code}</b> <em>{phaseShort(ph.name)}</em><small>{P[ph.a].index}–{P[ph.b].index}</small>
          </span>
        ))}
      </div>
    </div>
  );
}

function TopBar({ wide }: { wide: boolean }) {
  return (
    <header className="topbar">
      <div className="brand">
        <h1>Chianti Logbook</h1>
        <p className="sub">Training for the {DATA.race.name} · {day(DATA.race.date, true)}</p>
      </div>
      {wide && <Track />}
      <div className="countdown">
        <b>{Math.floor(DATA.race.weeks_to_go)} weeks</b>
        <span className="eyebrow">to the start line</span>
      </div>
    </header>
  );
}

function LastRace() {
  const race = DATA.diary.map(raceOf).filter(Boolean).pop();
  if (!race) return null;
  return (
    <div className="race-banner">
      <span aria-hidden="true">▲</span>
      <div><b>{race.name}</b><small>{day(race.date, true)} · {hm(race.mins / 60)} · {race.km} km · {race.vert.toLocaleString('en-GB')} m</small></div>
    </div>
  );
}

const TABS = [
  ['today', 'Today', 'M3 10.5 12 3l9 7.5V21h-6v-6H9v6H3z'],
  ['plan', 'Plan', 'M4 5h16v15H4zM4 9h16M8 3v4M16 3v4'],
  ['diary', 'Diary', 'M12 6c-2-1.5-5-2-8-1.5V19c3-.5 6 0 8 1.5 2-1.5 5-2 8-1.5V4.5C17 4 14 4.5 12 6zM12 6v14.5'],
  ['history', 'History', 'M5 20V12M10 20V7M15 20v-9M20 20V4'],
] as const;
type Tab = (typeof TABS)[number][0];

function Footer() {
  const c = DATA.cache;
  return (
    <footer>
      Generated by <code>uv run tl site</code> on {DATA.generated} from {c.n.toLocaleString('en-GB')} cached activities
      ({c.first} – {c.last}, {c.stale} day{c.stale === 1 ? '' : 's'} behind). Weekly hours are moving time across all sports;
      heart rate is COROS-measured where available, otherwise estimated from Strava relative effort (±3.5 bpm).
    </footer>
  );
}

export default function App() {
  const wide = useWide();
  const [tab, setTab] = useState<Tab>('today');
  const go = (t: Tab) => { setTab(t); window.scrollTo(0, 0); };

  if (wide) {
    return (
      <div className="app wide">
        <TopBar wide />
        <div className="row r1"><ThisWeek /><Guardrails /><Fitness /></div>
        <div className="row r2"><PlanChart /><Diary /></div>
        <div className="row r3"><Heatmap /><Ledger /></div>
        <Footer />
      </div>
    );
  }
  return (
    <div className="app phone">
      <TopBar wide={false} />
      <main>
        {tab === 'today' && <><LastRace /><ThisWeek><RailChips /></ThisWeek><Fitness compact /></>}
        {tab === 'plan' && <><section className="card"><Track /></section><PlanChart /></>}
        {tab === 'diary' && <Diary />}
        {tab === 'history' && <><Heatmap /><Ledger /><Footer /></>}
      </main>
      <nav className="tabbar" aria-label="Sections">
        {TABS.map(([key, label, d]) => (
          <button key={key} className={tab === key ? 'on' : ''} aria-current={tab === key ? 'page' : undefined} onClick={() => go(key)}>
            <svg viewBox="0 0 24 24" aria-hidden="true"><path d={d} /></svg>{label}
          </button>
        ))}
      </nav>
    </div>
  );
}
